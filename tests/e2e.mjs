// Headless e2e: node tests/e2e.mjs  (requires `npm run dev` running)
import { chromium } from 'playwright';
const BASE = process.env.URL || 'http://localhost:5173';
const out = new URL('../screenshots/', import.meta.url).pathname;
const results = []; const ok = (n, c) => { results.push([n, !!c]); console.log((c ? 'PASS ' : 'FAIL ') + n); };
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
const t = id => p.getByTestId(id); p.setDefaultTimeout(5000);
const setCode = async code => { for (let i = 0; i < 4; i++) { const cur = Number(await t('digit' + i).textContent()); const n = (Number(code[i]) - cur + 10) % 10; for (let k = 0; k < n; k++) await t('up' + i).click(); } };
await p.goto(BASE + '/?dev=1'); await p.waitForTimeout(800);
ok('title shows', await t('title').isVisible()); await p.screenshot({ path: out + '01-title.png' });
await t('enter').click(); await p.waitForTimeout(400);
ok('room 1 visible', await t('room1').isVisible());
const t1 = await t('timer').textContent();
await t('hint').click(); await p.waitForTimeout(4500);
const hl = await t('ghost-line').textContent(); ok('hint works without key: ' + hl, hl && !hl.includes('typing'));
await t('book2').click(); await t('portrait').click(); ok('portrait shows 1847', (await t('panel').textContent()).includes('1847'));
await t('cabinet').click(); await setCode('1234'); await t('unlock').click(); await p.waitForTimeout(300);
ok('1234 rejected', (await t('key').count()) === 0 && await t('room1').isVisible());
await setCode('1847'); await p.screenshot({ path: out + '02-library.png' }); await t('unlock').click(); await p.waitForTimeout(300);
ok('1847 opens cabinet', await t('key').isVisible());
await t('key').click({ force: true }); await t('key').click({ force: true, timeout: 500 }).catch(() => {}); await p.waitForTimeout(900);
ok('advanced exactly to room 2', await t('room2').isVisible() && (await t('progress').textContent()).includes('2/3'));
await t('potion-red').click(); await t('potion-blue').click(); await p.waitForTimeout(200);
ok('red->blue rejected (smoke)', await t('smoke').isVisible()); await p.screenshot({ path: out + '03-lab-smoke.png' });
await p.waitForTimeout(1500);
await t('lab-door').click(); await p.waitForTimeout(300); ok('locked door does not advance', await t('room2').isVisible());
await t('potion-green').click(); await t('potion-red').click(); await p.waitForTimeout(1500);
await t('potion-blue').click(); await t('potion-red').click(); await p.waitForTimeout(200);
await p.screenshot({ path: out + '04-lab-solved.png' });
await t('lab-door').click(); await p.waitForTimeout(900);
ok('blue->red advances to room 3', await t('room3').isVisible() && (await t('progress').textContent()).includes('3/3'));
await p.screenshot({ path: out + '05-crypt.png' });
await t('door-shadows').click(); await p.waitForTimeout(150); ok('shadows = jumpscare', await t('jumpscare').isVisible());
await p.screenshot({ path: out + '06-jumpscare.png' }); await p.waitForTimeout(800);
await t('door-flames').click(); await p.waitForTimeout(900); ok('flames rejected, still room 3', await t('room3').isVisible());
const t2 = await t('timer').textContent(); ok(`timer kept running across rooms (${t1} -> ${t2})`, t1 !== t2 && t1 === '3:00');
await t('door-silence').click(); await p.waitForTimeout(2200);
ok('silence = victory', await t('win').isVisible()); ok('rank shown', (await t('rank').textContent()).length > 3);
await p.screenshot({ path: out + '07-victory.png' });
await t('play-again').click(); await p.waitForTimeout(400);
ok('restart resets to room 1, 3:00, 0 hints', await t('room1').isVisible() && (await t('timer').textContent()) === '3:00' && (await t('progress').textContent()).includes('1/3'));
await t('cabinet').click(); ok('lock reset to 0000', (await Promise.all([0,1,2,3].map(i => t('digit'+i).textContent()))).join('') === '0000');
await t('dev-room2').click(); await t('dev-5s').click(); await p.waitForTimeout(6000);
ok('timeout -> defeat', await t('lose').isVisible()); await p.screenshot({ path: out + '08-defeat.png' });
await t('try-again').click(); await p.waitForTimeout(400); ok('try again restarts', await t('room1').isVisible());
await p.setViewportSize({ width: 1280, height: 720 }); await p.screenshot({ path: out + '09-room1-1280x720.png' });
const box = await t('room1').boundingBox(); ok('fits 1280x720 laptop', box && box.y + box.height <= 720);
ok('no page errors ' + errs.join('|'), errs.length === 0);
await b.close();
const f = results.filter(r => !r[1]).length; console.log(`\n${results.length - f}/${results.length} passed`); process.exit(f ? 1 : 0);
